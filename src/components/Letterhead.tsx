import type { ReactNode } from "react";
import { Printer } from "lucide-react";
import { apiPost } from "@/lib/api-client";
import { useAuth } from "@/hooks/useAuth";
import { Button } from "@/components/ui/button";

/**
 * Toolbar above every printable document. "Print / save as PDF" records the print in the
 * audit log, then opens the browser's print dialog (choose "Save as PDF" to get a file).
 * Hidden on paper.
 */
export function PrintToolbar({
  document,
  reference,
  children,
}: {
  document: string;
  reference?: string | null;
  children?: ReactNode;
}) {
  function print() {
    // Fire-and-forget: a failure to record must never stop someone printing.
    apiPost("/api/audit-log/document-export", { document, reference: reference ?? null }).catch(
      () => undefined,
    );
    window.print();
  }
  return (
    <div className="flex flex-wrap items-center gap-2 print:hidden">
      <Button onClick={print}>
        <Printer />
        Print / save as PDF
      </Button>
      {children}
      <p className="w-full text-xs text-muted-foreground">
        In the print dialog choose “Save as PDF” as the destination to download a PDF file. A4
        portrait is recommended.
      </p>
    </div>
  );
}

/** Closing block of every document: who produced it and when, for traceability. */
export function DocumentFooter({ note }: { note?: string }) {
  const { displayName, email } = useAuth();
  const generated = new Date().toLocaleString("en-GB", {
    day: "2-digit",
    month: "long",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
  return (
    <div className="mt-8 border-t border-neutral-400 pt-3 text-[11px] leading-5 text-neutral-600">
      <p>
        Generated by {displayName || email || "a system user"} on {generated} from the UNZA CICT
        Equipment Specification System.
      </p>
      {note && <p>{note}</p>}
      <p>
        University of Zambia · Centre for Information &amp; Communication Technologies · Great East
        Road Campus, Lusaka, Zambia
      </p>
    </div>
  );
}

/** Table styled for print: ruled rows, header repeated on every page. */
export function DocumentTable({
  headers,
  rows,
  empty = "No records.",
}: {
  headers: string[];
  rows: ReactNode[][];
  empty?: string;
}) {
  return (
    <table className="doc-table w-full border-collapse text-[12px] text-black">
      <thead>
        <tr className="border-b-2 border-black text-left">
          {headers.map((h) => (
            <th key={h} className="px-1.5 py-1.5 align-bottom font-semibold">
              {h}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.length === 0 ? (
          <tr>
            <td colSpan={headers.length} className="px-1.5 py-4 text-center text-neutral-600">
              {empty}
            </td>
          </tr>
        ) : (
          rows.map((cells, i) => (
            <tr key={i} className="border-b border-neutral-300 align-top">
              {cells.map((cell, j) => (
                <td key={j} className="px-1.5 py-1.5">
                  {cell}
                </td>
              ))}
            </tr>
          ))
        )}
      </tbody>
    </table>
  );
}

