-- Extends the request lifecycle past CICT technical approval into a real
-- procurement pipeline (quotations -> evaluation -> purchase -> stores
-- receipt -> CICT verification), and adds the "on behalf of" link so spec
-- recommendation can be based on the actual end-user's position level
-- instead of always the requester's own.

ALTER TABLE requests ADD COLUMN on_behalf_of_id uuid REFERENCES users(id) ON DELETE SET NULL;

ALTER TABLE requests DROP CONSTRAINT requests_status_check;
ALTER TABLE requests ADD CONSTRAINT requests_status_check CHECK (status IN
  ('draft','pending_manager','pending_cict','needs_clarification','approved',
   'rejected','withdrawn','procurement','purchased','in_stores','completed','return_required'));

ALTER TABLE user_roles DROP CONSTRAINT user_roles_role_check;
ALTER TABLE user_roles ADD CONSTRAINT user_roles_role_check CHECK (role IN
  ('requester','manager','cict_reviewer','cict_manager','procurement','auditor','admin',
   'stores','cict_support'));

-- Generalises V5's per-request-only sequence into one keyed by (prefix, year),
-- reused below for EVAL/VERIFY reference codes. The request reference itself
-- is no longer generated by this system (it's now the CICT Help Desk ticket
-- number, entered by the requester), so the old table is dropped rather than
-- carried forward.
DROP TABLE IF EXISTS request_reference_sequences;
CREATE TABLE reference_sequences (
  prefix text NOT NULL,
  year integer NOT NULL,
  last_value integer NOT NULL DEFAULT 0,
  PRIMARY KEY (prefix, year)
);

CREATE TABLE request_quotations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  vendor_name text NOT NULL,
  amount numeric NOT NULL,
  currency text NOT NULL DEFAULT 'ZMW',
  notes text,
  submitted_by uuid REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE quotation_evaluations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE,
  quotation_id uuid NOT NULL REFERENCES request_quotations(id) ON DELETE CASCADE,
  result text NOT NULL CHECK (result IN ('pass','fail')),
  notes text,
  evaluated_by uuid REFERENCES users(id) ON DELETE SET NULL,
  evaluated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE request_purchases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  quotation_id uuid REFERENCES request_quotations(id) ON DELETE SET NULL,
  purchase_order_number text,
  vendor_name text NOT NULL,
  amount numeric NOT NULL,
  currency text NOT NULL DEFAULT 'ZMW',
  purchased_by uuid REFERENCES users(id) ON DELETE SET NULL,
  purchased_at timestamptz NOT NULL DEFAULT now(),
  notes text
);

CREATE TABLE request_stores_receipts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  purchase_id uuid REFERENCES request_purchases(id) ON DELETE SET NULL,
  received_by uuid REFERENCES users(id) ON DELETE SET NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  condition_notes text
);

CREATE TABLE request_verifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE,
  request_id uuid NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  stores_receipt_id uuid REFERENCES request_stores_receipts(id) ON DELETE SET NULL,
  result text NOT NULL CHECK (result IN ('pass','needs_return')),
  notes text,
  verified_by uuid REFERENCES users(id) ON DELETE SET NULL,
  verified_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX request_quotations_request_idx ON request_quotations(request_id);
CREATE INDEX quotation_evaluations_quotation_idx ON quotation_evaluations(quotation_id);
CREATE INDEX request_purchases_request_idx ON request_purchases(request_id);
CREATE INDEX request_stores_receipts_request_idx ON request_stores_receipts(request_id);
CREATE INDEX request_verifications_request_idx ON request_verifications(request_id);
